#!/usr/bin/env node
/**
 * Brings the real design into stage 4, so a page drawn from the sitemap wears exactly what ships.
 *
 *   node scripts/sync-themes.mjs      # runs before `dev` and `build` (predev / prebuild)
 *
 * Copies src/themes/<id>/theme.css + fonts.css (the real app's, generated from its DESIGN.md by
 * `npm run design:sync`) into app/themes/<id>.css, and the theme's font files and art into
 * public/. All outputs are gitignored: a token edit in DESIGN.md reaches this stage on its next
 * build, with no copy to keep in step by hand.
 */
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(HERE, '../..');
const OUT_CSS = path.join(HERE, 'app/themes');
/** Under a path prefix (stages/next.config.base.ts) the copied CSS must point at prefixed files. */
const BASE = process.env.NEXT_PUBLIC_BASE_PATH ?? '';
const prefixed = (css) => (BASE ? css.replace(/url\((["']?)\/(fonts|assets)\//g, `url($1${BASE}/$2/`) : css);
/** The site's one design (src/themes/registry.ts). */
const THEME = 'botanical-deco';

rmSync(OUT_CSS, { recursive: true, force: true });
mkdirSync(OUT_CSS, { recursive: true });

const dir = path.join(REPO, 'src/themes', THEME);
const css = ['fonts.css', 'theme.css'].map((f) => readFileSync(path.join(dir, f), 'utf8'));
writeFileSync(path.join(OUT_CSS, `${THEME}.css`), `/* Copied from src/themes/${THEME}/ by scripts/sync-themes.mjs. Do not edit. */\n${prefixed(css.join('\n'))}`);
for (const sub of ['fonts', 'assets/art']) {
  const from = path.join(REPO, 'public', sub, THEME);
  const to = path.join(HERE, 'public', sub);
  // The whole folder, so a design that was removed does not linger from an earlier build.
  rmSync(to, { recursive: true, force: true });
  if (existsSync(from)) cpSync(from, path.join(to, THEME), { recursive: true });
}
writeFileSync(path.join(OUT_CSS, 'index.css'), `/* Generated by scripts/sync-themes.mjs. */\n@import "./${THEME}.css";\n`);
console.log(`sync-themes: ${THEME}`);
