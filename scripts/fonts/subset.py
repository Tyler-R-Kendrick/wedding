#!/usr/bin/env python3
"""
Subset the site's web fonts. Run by hand; nothing in the build calls this.

    python3 -m venv .venv-fonts && .venv-fonts/bin/pip install fonttools==4.55.3 brotli==1.1.0
    .venv-fonts/bin/python scripts/fonts/subset.py            # write public/fonts/** and the @font-face rules
    .venv-fonts/bin/python scripts/fonts/subset.py --check    # exit 1 if the committed output is stale
    .venv-fonts/bin/python scripts/fonts/subset.py --measure  # the source files: size, glyphs, axes, features, hinting

What it reads
    scripts/fonts/src/<theme>/*.woff2   the fonts as they came from their foundries (never served)
    scripts/fonts/fonts.json            per font: the CSS face it serves, the axis ranges, OpenType features
                                        and characters the site uses (how each was found is in README.md)

What it writes (commit all of it)
    public/fonts/<theme>/<name>-core.woff2   ASCII and the punctuation and letters the pages use; preloaded
    public/fonts/<theme>/<name>-ext.woff2    the rest of Latin-1 and Latin Extended-A the source has; fetched
                                             only by a page that shows one of its characters (unicode-range)
    src/themes/<theme>/fonts.css             the @font-face rules between the GENERATED markers; each
                                             names its file by content hash (`?v=`). A preloaded file's
                                             address in src/themes/registry.ts has to be the same one
                                             (tests/unit/fonts.test.ts says so when it is not).

Rerun it when
    * copy starts using a character outside `chars` in fonts.json (tests/unit/fonts.test.ts says which);
    * a stylesheet uses a weight, optical size or OpenType feature outside what fonts.json lists;
    * a source font is replaced or upgraded.

Rules it keeps
    * A character goes in exactly one file, and each unicode-range lists exactly the characters its
      file holds (plus, for the core, the invisible spaces a browser draws from any face). Both files of a face share one family name, so no fallback face sits between them.
    * Every character the pages render today is in the core file. Text is shaped per file, so a
      kerning pair cannot span two files: with the used letters together, today's words are unchanged.
    * An axis is narrowed to the range in use and pinned only where one value is used.
    * Hinting is kept unless fonts.json says `"hinting": "drop"` (it changes rendering on Windows).
    * A font whose licence reserves its name (OFL "Reserved Font Name") is renamed inside the file.
"""
import argparse, hashlib, io, json, os, re, sys
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.join(ROOT, 'scripts', 'fonts')
BEGIN = '/* GENERATED by scripts/fonts/subset.py: do not edit between these markers. */'
END = '/* END GENERATED */'

ASCII = set(range(0x20, 0x7F))
LATIN1 = set(range(0xA0, 0x100))
LATIN_EXT_A = set(range(0x100, 0x180))
MARKS = set(range(0x300, 0x370)) | {0x2C6, 0x2DA, 0x2DC}
# Spaces and format characters. No crawl of the pages sees these: the browser's own controls use
# them (a date-and-time field puts U+202F before AM/PM). A font kept the ones it has, and, more to
# the point, the core face CLAIMS all of them in its unicode-range whether it has a glyph or not:
# a browser draws a space it has no glyph for from the face's own space, scaled, but only if the
# face is allowed that character. Left out of the range, the system font's wider space was used and
# the AM/PM placeholder moved 3 px. This is the one place a range lists what its file lacks.
SPACES = set(range(0x2000, 0x2010)) | set(range(0x2028, 0x2030)) | set(range(0x205F, 0x2065)) | {0xFEFF}


def ranges(cps):
    """`U+20-7E, U+A0, …` for a set of code points, listing only what is given."""
    out, cps = [], sorted(cps)
    i = 0
    while i < len(cps):
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1:
            j += 1
        out.append(f'U+{cps[i]:X}' if i == j else f'U+{cps[i]:X}-{cps[j]:X}')
        i = j + 1
    return ', '.join(out)


def features_of(font):
    tags = set()
    for table in ('GSUB', 'GPOS'):
        if table in font and font[table].table.FeatureList:
            tags |= {r.FeatureTag for r in font[table].table.FeatureList.FeatureRecord}
    return tags


def measure(path):
    font = TTFont(path)
    cmap = font.getBestCmap()
    axes = [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in font['fvar'].axes] if 'fvar' in font else []
    hint_tables = {t: len(font.getTableData(t)) for t in ('fpgm', 'prep', 'cvt ') if t in font}
    instructions = sum(len(font['glyf'][g].program.getBytecode()) for g in font.getGlyphOrder() if hasattr(font['glyf'][g], 'program') and font['glyf'][g].program) if 'glyf' in font else 0
    return {'bytes': os.path.getsize(path), 'glyphs': font['maxp'].numGlyphs, 'characters': len(cmap), 'axes': axes, 'features': sorted(features_of(font)), 'hintTables': hint_tables, 'glyphInstructionBytes': instructions, 'family': font['name'].getDebugName(1)}


def rename(font, new_family):
    """An OFL Reserved Font Name may not be carried by a modified version, and a subset is one."""
    old = font['name'].getDebugName(16) or font['name'].getDebugName(1)
    for record in font['name'].names:
        if record.nameID in (1, 3, 4, 6, 16, 18, 21, 25):
            text = record.toUnicode()
            replaced = text.replace(old, new_family).replace(old.replace(' ', ''), new_family.replace(' ', ''))
            if replaced == text and record.nameID in (1, 4, 16):
                replaced = new_family
            record.string = replaced


def build_one(source, spec, cps, keep_features):
    """One output file: the given characters, the axes limited, the listed features, as woff2 bytes."""
    # recalcTimestamp=False everywhere: a file that differs only by the minute it was written would
    # make `--check` report every font as stale.
    font = TTFont(source, recalcTimestamp=False, recalcBBoxes=False)
    # The font-wide box and flags as the foundry set them. Left alone, saving a subset shrinks the
    # box to the glyphs that remain and clears a flag, and a rasteriser that reads either draws a
    # few edge pixels differently although no outline moved (measured: 23 pixels, 3 levels).
    head = {k: getattr(font['head'], k) for k in ('flags', 'xMin', 'yMin', 'xMax', 'yMax')}
    instanced = False
    if 'fvar' in font and spec.get('axes'):
        limits = {}
        for axis in font['fvar'].axes:
            want = spec['axes'].get(axis.axisTag)
            if want is None:
                continue
            limits[axis.axisTag] = want if isinstance(want, (int, float)) else (want[0], want[1])
        if limits:
            font = instancer.instantiateVariableFont(TTFont(source, recalcTimestamp=False), limits, inplace=False)
            # Through bytes and back: the subsetter cannot read the instancer's variation table in
            # place (KeyError on the first glyph without deltas, fontTools 4.55).
            font.flavor = None
            buf = io.BytesIO()
            font.save(buf)
            buf.seek(0)
            font = TTFont(buf, recalcTimestamp=False, recalcBBoxes=False)
            instanced = True
    options = subset.Options()
    options.layout_features = sorted(keep_features)
    options.hinting = spec.get('hinting', 'keep') != 'drop'
    options.desubroutinize = True
    options.notdef_outline = True
    options.glyph_names = False
    options.legacy_kern = False
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17, 25]
    options.name_languages = ['*']
    options.recalc_bounds = False
    options.recalc_timestamp = False
    options.drop_tables += ['DSIG', 'meta', 'FFTM']
    options.flavor = 'woff2'
    sub = subset.Subsetter(options)
    sub.populate(unicodes=sorted(cps))
    sub.subset(font)
    if not instanced:
        for key, value in head.items():
            setattr(font['head'], key, value)
    if spec.get('rename'):
        rename(font, spec['rename'])
    font.flavor = 'woff2'
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def plan(spec, config):
    """Which characters go where for one face. Only characters the source really has."""
    source = os.path.join(HERE, 'src', spec['source'])
    have = set(TTFont(source).getBestCmap())
    used = set(config['chars']) | set(spec.get('chars', []))
    keep = have & (ASCII | LATIN1 | LATIN_EXT_A | MARKS | SPACES | used)
    # A combining accent is shaped with the letter before it, so it has to travel with ASCII: a name
    # typed as `e` + U+0301 is one glyph cluster, and a cluster cannot span two files.
    core = keep & (ASCII | MARKS | SPACES | used)
    return source, core, keep - core, have - keep


def versioned(file, data):
    """The address a page asks for: the file, named by its content. next.config.ts serves `/fonts/…?v=`
    as immutable, so a browser never asks again, and a regenerated file arrives under a new URL."""
    return f'/fonts/{file}?v={hashlib.sha256(data).hexdigest()[:12]}'


def face_css(spec, url, cps):
    lines = ['@font-face {', f'  font-family: {spec["family"]};', f'  src: url("{url}") format("woff2");', f'  font-weight: {spec["weight"]};', f'  font-style: {spec["style"]};', f'  font-display: {spec["display"]};', f'  unicode-range: {ranges(cps)};', '}']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--measure', action='store_true')
    parser.add_argument('--out', help='write the fonts here instead of public/fonts, and leave the stylesheets alone (a dry run)')
    args = parser.parse_args()
    config = json.load(open(os.path.join(HERE, 'fonts.json')))

    if args.measure:
        for spec in config['fonts']:
            print(spec['source'], json.dumps(measure(os.path.join(HERE, 'src', spec['source']))))
        return 0

    stale, report, css = [], [], {}
    for spec in config['fonts']:
        theme = spec['source'].split('/')[0]
        source, core, ext, dropped = plan(spec, config)
        keep_features = set(spec['features']) & features_of(TTFont(source))
        entry = {'source': spec['source'], 'sourceBytes': os.path.getsize(source), 'dropped': len(dropped), 'files': []}
        for part, cps in (('core', core), ('ext', ext)):
            if not cps:
                continue
            name = f'{theme}/{spec["name"]}-{part}.woff2'
            data = build_one(source, spec, cps, keep_features)
            # Check the file, not the plan: what a tool was asked for and what it wrote can differ.
            written = TTFont(io.BytesIO(data))
            got = set(written.getBestCmap())
            if got != cps:
                raise SystemExit(f'{name}: holds {ranges(got ^ cps)} differently from its unicode-range')
            if spec.get('rename') and any(spec['reserved'] in r.toUnicode() for r in written['name'].names if r.nameID in (1, 4, 6, 16)):
                raise SystemExit(f'{name}: still carries the reserved name {spec["reserved"]!r}')
            if 'fvar' in written:
                for axis in written['fvar'].axes:
                    want = spec.get('axes', {}).get(axis.axisTag)
                    if isinstance(want, list) and (axis.minValue, axis.maxValue) != (want[0], want[1]):
                        raise SystemExit(f'{name}: {axis.axisTag} is {axis.minValue}-{axis.maxValue}, asked for {want}')
            target = os.path.join(args.out or os.path.join(ROOT, 'public', 'fonts'), name)
            if args.check:
                if not os.path.exists(target) or open(target, 'rb').read() != data:
                    stale.append(name)
            else:
                os.makedirs(os.path.dirname(target), exist_ok=True)
                open(target, 'wb').write(data)
            entry['files'].append({'file': name, 'bytes': len(data), 'characters': len(cps), 'glyphs': written['maxp'].numGlyphs, 'features': sorted(features_of(written))})
            css.setdefault(theme, []).append(face_css(spec, versioned(name, data), cps | SPACES if part == 'core' else cps))
        report.append(entry)

    for theme, faces in ([] if args.out else css.items()):
        path = os.path.join(ROOT, 'src', 'themes', theme, 'fonts.css')
        text = open(path).read()
        block = BEGIN + '\n' + '\n\n'.join(faces) + '\n\n' + END
        if BEGIN not in text:
            raise SystemExit(f'{path}: no GENERATED markers')
        new = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _: block, text, flags=re.S)
        if args.check:
            if new != text:
                stale.append(os.path.relpath(path, ROOT))
        else:
            open(path, 'w').write(new)

    if args.check:
        print('stale: ' + ', '.join(stale) if stale else 'fonts are up to date')
        return 1 if stale else 0
    if not args.out:
        json.dump(report, open(os.path.join(HERE, 'report.json'), 'w'), indent=1)
    for entry in report:
        total = sum(f['bytes'] for f in entry['files'])
        print(f"{entry['source']:55} {entry['sourceBytes']:>6} -> {total:>6}  ({', '.join(str(f['bytes']) for f in entry['files'])})")
    return 0


if __name__ == '__main__':
    sys.exit(main())
